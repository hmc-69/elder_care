import { useCallback, useEffect, useState } from 'react'
import { useParams, Link } from 'react-router-dom'
import { ArrowLeft, Check, Clock, PhoneCall, X } from 'lucide-react'
import { ErrorState, FeedbackMessages, LoadingSkeleton, PageHeader, StatusBadge } from '../components/ui'
import { sosService } from '../services/sosService'
import type { EmergencyEvent, FamilyElderSosView } from '../types/sos'

function formatDateTime(iso: string) {
  const d = new Date(iso)
  if (Number.isNaN(d.getTime())) return iso
  return d.toLocaleString([], {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  })
}

export function FamilyElderSosPage() {
  const { elderId = '' } = useParams()
  const [data, setData] = useState<FamilyElderSosView | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState(false)
  const [actionMessage, setActionMessage] = useState('')
  const [actionError, setActionError] = useState('')
  const [acting, setActing] = useState(false)

  // Resolve modal state
  const [showResolveModal, setShowResolveModal] = useState(false)
  const [resolutionNotes, setResolutionNotes] = useState('')

  const loadData = useCallback(async () => {
    try {
      const res = await sosService.getFamilyElderSos(elderId)
      setData(res)
      setError(false)
    } catch {
      setError(true)
    } finally {
      setLoading(false)
    }
  }, [elderId])

  useEffect(() => {
    void loadData()
  }, [loadData])

  // Polling every 15s to update status
  useEffect(() => {
    const timer = setInterval(() => {
      void loadData()
    }, 15000)
    return () => clearInterval(timer)
  }, [loadData])

  async function handleAcknowledge(alertId: string) {
    setActing(true)
    setActionMessage('')
    setActionError('')
    try {
      const res = await sosService.acknowledgeSos(alertId)
      setActionMessage(res.message)
      await loadData()
    } catch (err) {
      setActionError(err instanceof Error ? err.message : 'Could not acknowledge alert.')
      await loadData()
    } finally {
      setActing(false)
    }
  }

  async function handleResolve(alertId: string) {
    setActing(true)
    setActionMessage('')
    setActionError('')
    try {
      const res = await sosService.resolveSos(alertId, resolutionNotes)
      setActionMessage(res.message)
      setShowResolveModal(false)
      setResolutionNotes('')
      await loadData()
    } catch (err) {
      setActionError(err instanceof Error ? err.message : 'Could not resolve alert.')
      await loadData()
    } finally {
      setActing(false)
    }
  }

  return (
    <div className="app-page family-elder-sos-page">
      <Link className="text-link back-link" to="/family/emergencies">
        <ArrowLeft size={16} /> Back to all emergency alerts
      </Link>

      <PageHeader
        eyebrow="CONNECTED ELDER EMERGENCY RECORD"
        title={data ? `${data.elder.name}'s SOS History` : 'Emergency Record'}
        description="Review active emergency status and past emergency records for your connected elder."
      />

      <aside className="emergency-disclaimer-banner" role="note" aria-label="Emergency disclaimer">
        <PhoneCall size={20} className="disclaimer-icon" aria-hidden="true" />
        <div>
          <strong>Emergency Notification Disclaimer:</strong>
          <p>
            This dashboard displays in-app events generated by the elder. It does <strong>not</strong> contact 911, dispatch ambulances, or alert police. If immediate physical intervention is required, call <strong>911</strong> directly.
          </p>
        </div>
      </aside>

      <FeedbackMessages
        message={actionMessage}
        error={actionError}
        onDismiss={() => { setActionMessage(''); setActionError('') }}
      />

      {loading ? (
        <LoadingSkeleton rows={4} />
      ) : error || !data ? (
        <ErrorState
          title="Unable to load emergency information for this connected elder."
          onRetry={() => { setLoading(true); void loadData() }}
        />
      ) : (
        <>
          {/* Active Alert Section if present */}
          {data.activeEvent ? (
            <section className="sos-active-card" aria-labelledby="elder-active-alert-title">
              <div className="sos-active-header">
                <div className="sos-pulsing-badge" aria-hidden="true" />
                <div>
                  <span className="panel-overline">URGENT ALERT</span>
                  <h2 id="elder-active-alert-title">
                    {data.elder.name} Needs Immediate Help
                  </h2>
                </div>
                <StatusBadge status={data.activeEvent.status === 'ACKNOWLEDGED' ? 'warning' : 'danger'}>
                  {data.activeEvent.status}
                </StatusBadge>
              </div>

              <div className="sos-active-details">
                <p>
                  <Clock size={16} aria-hidden="true" />
                  Triggered at <strong>{formatDateTime(data.activeEvent.triggeredAt)}</strong>
                </p>

                {data.activeEvent.notes && (
                  <p><strong>Elder note:</strong> <em>"{data.activeEvent.notes}"</em></p>
                )}

                {data.activeEvent.status === 'ACKNOWLEDGED' && data.activeEvent.acknowledgedBy && (
                  <p className="sos-acknowledged-text">
                    ✓ Acknowledged by <strong>{data.activeEvent.acknowledgedBy.name}</strong> at {formatDateTime(data.activeEvent.acknowledgedAt || '')}.
                  </p>
                )}
              </div>

              <div className="active-emergency-actions">
                {data.activeEvent.status === 'ACTIVE' && (
                  <button
                    type="button"
                    className="button button-warning button-small"
                    disabled={acting}
                    onClick={() => void handleAcknowledge(data.activeEvent!.id)}
                  >
                    {acting ? 'Acknowledging…' : 'Acknowledge Alert'}
                  </button>
                )}

                <button
                  type="button"
                  className="button button-primary button-small"
                  disabled={acting}
                  onClick={() => setShowResolveModal(true)}
                >
                  Resolve Emergency
                </button>
              </div>
            </section>
          ) : (
            <div className="sos-all-clear">
              <Check size={26} className="all-clear-icon" aria-hidden="true" />
              <div>
                <h3>No Active Alert</h3>
                <p>{data.elder.name} does not currently have any active emergency alerts.</p>
              </div>
            </div>
          )}

          {/* Past History */}
          <section className="dashboard-panel" aria-labelledby="history-heading">
            <div className="panel-heading">
              <div>
                <span className="panel-icon warm">
                  <Clock size={19} aria-hidden="true" />
                </span>
                <div>
                  <p className="panel-overline">PAST EVENTS</p>
                  <h2 id="history-heading">Emergency History</h2>
                </div>
              </div>
            </div>

            {data.history.length === 0 ? (
              <p className="sos-history-empty">No past emergency events recorded for this elder.</p>
            ) : (
              <ul className="sos-history-list">
                {data.history.map((item: EmergencyEvent) => (
                  <li key={item.id} className={`sos-history-item status-${item.status.toLowerCase()}`}>
                    <div className="sos-history-meta">
                      <strong>{formatDateTime(item.triggeredAt)}</strong>
                      <StatusBadge
                        status={
                          item.status === 'RESOLVED'
                            ? 'success'
                            : item.status === 'CANCELLED'
                              ? 'neutral'
                              : item.status === 'ACKNOWLEDGED'
                                ? 'warning'
                                : 'danger'
                        }
                      >
                        {item.status}
                      </StatusBadge>
                    </div>

                    <div className="sos-history-details">
                      {item.notes && <p><strong>Notes:</strong> {item.notes}</p>}
                      {item.status === 'CANCELLED' && item.cancellationReason && (
                        <p>Reason: {item.cancellationReason}</p>
                      )}
                      {item.status === 'RESOLVED' && (
                        <p>
                          Resolved {item.resolvedAt ? `at ${formatDateTime(item.resolvedAt)}` : ''}
                          {item.resolvedBy ? ` by ${item.resolvedBy.name}` : ''}
                        </p>
                      )}
                    </div>
                  </li>
                ))}
              </ul>
            )}
          </section>

          {/* Resolve Modal */}
          {showResolveModal && data.activeEvent && (
            <div className="modal-scrim" role="dialog" aria-modal="true" aria-labelledby="resolve-elder-modal-title">
              <div className="modal-dialog">
                <div className="modal-header">
                  <h3 id="resolve-elder-modal-title">Resolve Emergency for {data.elder.name}</h3>
                  <button
                    type="button"
                    className="icon-button"
                    aria-label="Close dialog"
                    onClick={() => setShowResolveModal(false)}
                  >
                    <X size={20} />
                  </button>
                </div>
                <div className="modal-body">
                  <p>Confirm that {data.elder.name} is safe and that this emergency is concluded.</p>
                  <label htmlFor="elder-resolve-notes" className="form-label">
                    Resolution summary (optional):
                  </label>
                  <input
                    id="elder-resolve-notes"
                    type="text"
                    className="text-input"
                    placeholder="e.g. Visited and verified elder is safe"
                    maxLength={500}
                    value={resolutionNotes}
                    onChange={(e) => setResolutionNotes(e.target.value)}
                  />
                </div>
                <div className="modal-actions">
                  <button
                    type="button"
                    className="button button-secondary"
                    onClick={() => setShowResolveModal(false)}
                    disabled={acting}
                  >
                    Cancel
                  </button>
                  <button
                    type="button"
                    className="button button-primary"
                    onClick={() => void handleResolve(data.activeEvent!.id)}
                    disabled={acting}
                  >
                    {acting ? 'Resolving…' : 'Confirm Resolution'}
                  </button>
                </div>
              </div>
            </div>
          )}
        </>
      )}
    </div>
  )
}
